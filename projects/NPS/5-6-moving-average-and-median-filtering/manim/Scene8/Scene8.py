from manim import *
import numpy as np


class Scene8(Scene):
    def construct(self):
        self.camera.background_color = "#0F1116"

        # ----------------------------------------------------------------
        # Helper
        # ----------------------------------------------------------------
        def make_signal(axes, x_arr, y_arr, color=WHITE, stroke_width=3):
            points = [axes.c2p(x, y) for x, y in zip(x_arr, y_arr)]
            mob = VMobject(stroke_color=color, stroke_width=stroke_width, fill_opacity=0)
            mob.set_points_as_corners(points)
            return mob

        # ----------------------------------------------------------------
        # Common dimensions
        # ----------------------------------------------------------------
        plot_width = 6.0
        plot_height = 3.0

        # ----------------------------------------------------------------
        # LEFT PANEL – high-frequency noise + moving-average window
        # ----------------------------------------------------------------
        left_axes = Axes(
            x_range=[0, 10, 1],
            y_range=[-0.2, 1.6, 0.5],
            x_length=plot_width,
            y_length=plot_height,
            axis_config={"include_numbers": False, "include_ticks": False, "stroke_color": GREY, "stroke_width": 2},
            tips=False,
        ).move_to(LEFT * 3.25)

        np.random.seed(42)
        noise_n = 200
        noise_x = np.linspace(0, 10, noise_n)
        noise_y = np.cumsum(np.random.randn(noise_n) * 0.1) + 0.5
        noise_y = (noise_y - noise_y.min()) / (noise_y.max() - noise_y.min()) * 1.0 + 0.2

        left_signal = make_signal(left_axes, noise_x, noise_y, color=WHITE, stroke_width=2.5)

        win_left_start = 0.2
        win_right_start = 1.2
        win_mid_y_left = (left_axes.y_range[0] + left_axes.y_range[1]) / 2
        win_center_start = (win_left_start + win_right_start) / 2
        window_left = Rectangle(
            width=left_axes.c2p(win_right_start, 0)[0] - left_axes.c2p(win_left_start, 0)[0],
            height=left_axes.c2p(0, left_axes.y_range[1])[1] - left_axes.c2p(0, left_axes.y_range[0])[1],
            stroke_color=YELLOW,
            stroke_width=2,
            fill_opacity=0,
        ).move_to(left_axes.c2p(win_center_start, win_mid_y_left))

        left_panel = VGroup(left_axes, left_signal, window_left)

        # ----------------------------------------------------------------
        # RIGHT PANEL – clean baseline with isolated spike + median window
        # ----------------------------------------------------------------
        right_axes = Axes(
            x_range=[0, 10, 1],
            y_range=[-0.2, 1.6, 0.5],
            x_length=plot_width,
            y_length=plot_height,
            axis_config={"include_numbers": False, "include_ticks": False, "stroke_color": GREY, "stroke_width": 2},
            tips=False,
        ).move_to(RIGHT * 3.25)

        x_fine = np.linspace(0, 10, 250)
        baseline = 0.2
        spike = 1.2 * np.exp(-0.5 * ((x_fine - 5) / 0.08) ** 2)
        y_right = baseline + spike
        right_signal = make_signal(right_axes, x_fine, y_right, color=WHITE, stroke_width=3)

        win_spike_left = 4.5
        win_spike_right = 5.5
        window_right = Rectangle(
            width=right_axes.c2p(win_spike_right, 0)[0] - right_axes.c2p(win_spike_left, 0)[0],
            height=right_axes.c2p(0, right_axes.y_range[1])[1] - right_axes.c2p(0, right_axes.y_range[0])[1],
            stroke_color=ORANGE,
            stroke_width=2,
            fill_opacity=0,
        ).move_to(right_axes.c2p(5.0, (right_axes.y_range[0] + right_axes.y_range[1]) / 2))

        right_panel = VGroup(right_axes, right_signal, window_right)

        # ----------------------------------------------------------------
        # BEAT 1 [0.00 – 3.04] – full split screen, no labels
        #   Duration: 3.04 seconds
        # ----------------------------------------------------------------
        self.play(
            FadeIn(left_panel),
            FadeIn(right_panel),
            run_time=max(0.05, 2.0)
        )
        self.wait(max(0.05, 1.04))

        # ----------------------------------------------------------------
        # BEAT 2 [3.04 – 5.46] – labels beneath panels
        #   Duration: 2.42 seconds
        # ----------------------------------------------------------------
        label_left = Text(
            "Random fluctuations → Moving Average",
            font_size=22, color=WHITE, weight="BOLD"
        )
        label_left.scale_to_fit_width(plot_width * 0.9)
        label_left.next_to(left_axes, DOWN, buff=0.4)

        label_right = Text(
            "Impulsive noise → Median",
            font_size=22, color=WHITE, weight="BOLD"
        )
        label_right.scale_to_fit_width(plot_width * 0.9)
        label_right.next_to(right_axes, DOWN, buff=0.4)

        self.play(
            Write(label_left),
            Write(label_right),
            run_time=max(0.05, 1.5)
        )
        self.wait(max(0.05, 0.92))

        # ----------------------------------------------------------------
        # BEAT 3 [5.46 – 11.20] – left brightens, window slides + trace
        #   Duration: 5.74 seconds
        #   Sub-tasks:
        #     0.20s: brightness change
        #     4.34s: window slides from left edge to right edge
        #     1.20s: hold
        # ----------------------------------------------------------------
        # Brighten left, dim right
        self.play(
            left_panel.animate.set_opacity(1.0),
            right_panel.animate.set_opacity(0.35),
            label_left.animate.set_opacity(1.0),
            label_right.animate.set_opacity(0.35),
            run_time=max(0.05, 0.2)
        )

        # Replace original left trace with a faint thin version
        left_signal_faint = left_signal.copy().set_stroke(width=1, opacity=0.3)
        self.remove(left_signal)
        self.add(left_signal_faint)

        # Compute moving-average smoothed trace
        ma_halfwidth = 0.5
        ma_y = np.zeros_like(noise_x)
        for i in range(len(noise_x)):
            mask = (noise_x >= noise_x[i] - ma_halfwidth) & (noise_x <= noise_x[i] + ma_halfwidth)
            if np.sum(mask) > 0:
                ma_y[i] = np.mean(noise_y[mask])
            else:
                ma_y[i] = noise_y[i]
        ma_signal_full = make_signal(left_axes, noise_x, ma_y, color=YELLOW, stroke_width=4)

        # Move the moving-average window from start to end
        win_end_left = 8.5
        win_end_right = 9.5
        win_end_center = (win_end_left + win_end_right) / 2
        window_end_pos = left_axes.c2p(win_end_center, win_mid_y_left)

        # Animate window slide + drawing the smoothed trace
        self.play(
            Create(ma_signal_full, rate_func=linear),
            window_left.animate.move_to(window_end_pos),
            run_time=max(0.05, 4.34)
        )
        self.wait(max(0.05, 1.20))

        # ----------------------------------------------------------------
        # BEAT 4 [11.20 – 16.92] – right brightens, median filter demo
        #   Duration: 5.72 seconds
        #   Sub-tasks:
        #     0.20s: brightness change
        #     0.50s: create sample dots
        #     2.00s: rearrange dots vertically (sort)
        #     0.50s: highlight median dot
        #     0.50s: shrink/spike dot
        #     0.50s: transform signal to flat (spike removed)
        #     Remainder: wait to 15.86 then hold to 16.92
        # ----------------------------------------------------------------
        # Dim left, brighten right
        self.play(
            left_panel.animate.set_opacity(0.35),
            left_signal_faint.animate.set_opacity(0.15),
            ma_signal_full.animate.set_opacity(0.35),
            label_left.animate.set_opacity(0.35),
            right_panel.animate.set_opacity(1.0),
            label_right.animate.set_opacity(1.0),
            run_time=max(0.05, 0.2)
        )

        # Sample points inside the median window
        mask_window = (x_fine >= win_spike_left) & (x_fine <= win_spike_right)
        x_in = x_fine[mask_window]
        y_in = y_right[mask_window]
        n_dots = 11
        indices = np.linspace(0, len(x_in) - 1, n_dots, dtype=int)
        sample_x = x_in[indices]
        sample_y = y_in[indices]

        dots = VGroup()
        for sx, sy in zip(sample_x, sample_y):
            dot = Dot(
                point=right_axes.c2p(sx, sy),
                radius=0.06, color=BLUE, fill_opacity=1
            )
            dots.add(dot)

        self.play(Create(dots), run_time=max(0.05, 0.5))

        # Sort dots by amplitude and rearrange vertically
        win_center_x = (win_spike_left + win_spike_right) / 2
        sorted_y = np.sort(sample_y)
        ranks = np.argsort(sample_y)    # ranks[0] = index of smallest original dot

        targets = []
        for i, dot in enumerate(dots):
            rank = np.where(ranks == i)[0][0]
            target_y = sorted_y[rank]
            pos = right_axes.c2p(win_center_x, target_y)
            targets.append((dot, pos))

        self.play(
            *[dot.animate.move_to(pos) for dot, pos in targets],
            run_time=max(0.05, 2.0)
        )

        # Highlight the median value
        median_idx = n_dots // 2
        median_dot_index = ranks[median_idx]
        median_dot = dots[median_dot_index]
        self.play(
            median_dot.animate.scale(2.5).set_color(YELLOW),
            run_time=max(0.05, 0.5)
        )

        # Discard the extreme spike dot (highest amplitude)
        extreme_dot_index = ranks[-1]
        extreme_dot = dots[extreme_dot_index]
        self.play(
            extreme_dot.animate.set_opacity(0).scale(0.1),
            run_time=max(0.05, 0.5)
        )

        # Remove the spike from the waveform itself
        y_flat = np.full_like(x_fine, baseline)
        flat_signal = make_signal(
            right_axes, x_fine, y_flat,
            color=WHITE, stroke_width=3
        )
        self.play(
            Transform(right_signal, flat_signal),
            run_time=max(0.05, 0.5)
        )

        # Wait to 15.86, then hold until 16.92
        # After transform: time elapsed in this beat =
        #   0.20 + 0.50 + 2.00 + 0.50 + 0.50 + 0.50 = 4.20
        # Remaining to 15.86: beat start 11.20 + ? = 15.86  → gap = 15.86 - (11.20+4.20) = 0.46
        self.wait(max(0.05, 0.46))
        # Hold from 15.86 to 16.92: 16.92 - 15.86 = 1.06
        self.wait(max(0.05, 1.06))

        # ----------------------------------------------------------------
        # BEAT 5 [16.92 – 20.90] – both panels equal, final comparison hold
        #   Duration: 3.98 seconds
        #   Sub-tasks:
        #     0.50s: restore brightness
        #     0.50s: clean up right panel dots + window
        #     2.98s: final hold
        # ----------------------------------------------------------------
        # Restore brightness to both panels
        self.play(
            left_panel.animate.set_opacity(1.0),
            left_signal_faint.animate.set_opacity(0.3),
            ma_signal_full.animate.set_opacity(1.0),
            label_left.animate.set_opacity(1.0),
            right_panel.animate.set_opacity(1.0),
            label_right.animate.set_opacity(1.0),
            run_time=max(0.05, 0.5)
        )

        # Clean up the right panel: remove dots and the median window
        self.play(
            FadeOut(VGroup(dots, window_right)),
            run_time=max(0.05, 0.5)
        )

        self.wait(max(0.05, 2.98))